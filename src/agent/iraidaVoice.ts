type AddressingStyle = 'lord' | 'lady' | 'neutral' | null;

export function getAddressingStyle(preferences: string | null): AddressingStyle {
  const match = preferences?.match(
    /(?:^|\n)\s*addressing_style\s*:\s*(lord|lady|neutral)\s*(?=\n|$)/i,
  );

  return (match?.[1]?.toLowerCase() as Exclude<AddressingStyle, null> | undefined) ?? null;
}

